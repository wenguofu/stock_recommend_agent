def seed_strategies():
    """导入策略数据"""
    db = SessionLocal()
    try:
        existing = {s.name for s in get_strategies(db)}
        created_count = 0

        for strategy_data in [YOUZI_STRATEGY, JIANPAN_STRATEGY, LIANGHUA_STRATEGY]:
            name = strategy_data['name']
            if name in existing:
                print(f"[种子] 策略已存在: {name}")
                continue

            strategy = create_strategy(
                db,
                name=name,
                description=strategy_data['description'],
                category=strategy_data['category'],
                doc_md=strategy_data['doc_md'],
                agent_configs=json.dumps(strategy_data['agent_configs'], ensure_ascii=False),
                sort_order=strategy_data['sort_order']
            )
            created_count += 1
            print(f"[种子] 创建策略: {strategy.name} (ID: {strategy.id}) - {len(strategy_data['agent_configs'])}个Agent")

        if created_count == 0:
            print("[种子] 所有策略已存在，无需创建")
        else:
            print(f"[种子] 成功创建 {created_count} 个策略")

    except Exception as e:
        print(f"[种子] 创建策略失败: {e}")
        import traceback
        traceback.print_exc()
    finally:
        db.close()


if __name__ == '__main__':
    seed_strategies()
